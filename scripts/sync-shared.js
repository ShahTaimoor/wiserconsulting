#!/usr/bin/env node
/**
 * Copies the canonical shared/tourist-visa/ runtime files into the client and
 * backend apps, which deploy separately and cannot import from outside their
 * own folder.
 *
 *   node scripts/sync-shared.js            copy files
 *   node scripts/sync-shared.js --check    exit 1 if a copy has drifted
 *
 * Line endings are normalised to LF on write and ignored on compare, so
 * Windows checkouts with core.autocrlf do not show false drift.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SOURCE = path.join(ROOT, 'shared', 'tourist-visa');
const FILES = ['questions.json', 'countries.json', 'engine.js', 'engine.d.ts'];
const MARKER = 'GENERATED.txt';
const MARKER_TEXT =
  'Generated by scripts/sync-shared.js from shared/tourist-visa/.\n' +
  'Do not edit these files here; change the canonical files and run the script again.\n';
const TARGETS = [
  path.join(ROOT, 'client', 'src', 'shared', 'tourist-visa'),
  path.join(ROOT, 'backend', 'shared', 'tourist-visa'),
];

const read = (file) => fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');

function sync({ source = SOURCE, targets = TARGETS } = {}) {
  for (const target of targets) {
    fs.mkdirSync(target, { recursive: true });
    for (const name of FILES) fs.writeFileSync(path.join(target, name), read(path.join(source, name)));
    fs.writeFileSync(path.join(target, MARKER), MARKER_TEXT);
  }
}

/** Returns a list of problems; empty means every copy matches the canonical files. */
function check({ source = SOURCE, targets = TARGETS } = {}) {
  const problems = [];
  for (const target of targets) {
    const rel = path.relative(ROOT, target) || target;
    if (!fs.existsSync(target)) {
      problems.push(`${rel}: missing (run node scripts/sync-shared.js)`);
      continue;
    }
    for (const name of FILES) {
      const copy = path.join(target, name);
      if (!fs.existsSync(copy)) problems.push(`${rel}/${name}: missing`);
      else if (read(copy) !== read(path.join(source, name))) problems.push(`${rel}/${name}: differs from shared/tourist-visa/${name}`);
    }
    if (!fs.existsSync(path.join(target, MARKER))) problems.push(`${rel}/${MARKER}: missing`);
    const expected = new Set([...FILES, MARKER]);
    for (const extra of fs.readdirSync(target).filter((n) => !expected.has(n))) {
      problems.push(`${rel}/${extra}: not part of the shared set`);
    }
  }
  return problems;
}

module.exports = { sync, check, FILES, TARGETS, SOURCE };

if (require.main === module) {
  if (process.argv.includes('--check')) {
    const problems = check();
    if (problems.length) {
      console.error('Shared Tourist Visa files are out of sync:\n  ' + problems.join('\n  '));
      process.exit(1);
    }
    console.log('Shared Tourist Visa files are in sync.');
  } else {
    sync();
    console.log('Synced shared/tourist-visa/ to:\n  ' + TARGETS.map((t) => path.relative(ROOT, t)).join('\n  '));
  }
}
